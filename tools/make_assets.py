#!/usr/bin/env python3
"""Generates the Navigate graphics.

Why generated and not handwritten: the path data of the rounded
squares (9 per glyph) and the TV banner are pure calculation —
typing by hand writes rounding errors into the SVG paths.

Usage:   python3 tools/make_assets.py
Result (idempotent, overwrites):
  app/src/main/res/drawable/ic_launcher_foreground.xml
  app/src/main/res/drawable/ic_launcher_legacy.xml
  app/src/main/res/mipmap-anydpi-v26/ic_launcher.xml
  app/src/main/res/mipmap-anydpi/ic_launcher.xml
  app/src/main/res/drawable-nodpi/banner.png
"""
from __future__ import annotations

import os

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "app", "src", "main", "res")

BG = "#10151C"
GLYPH = "#6EA8FE"
TEXT = "#E8EAED"

VECTOR_HEAD = (
    '<?xml version="1.0" encoding="utf-8"?>\n'
    '<!-- GENERATED by tools/make_assets.py — do not edit by hand. -->\n'
    '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
    '    android:width="{w}dp"\n'
    '    android:height="{h}dp"\n'
    '    android:viewportWidth="{vw}"\n'
    '    android:viewportHeight="{vh}">\n'
)


def rrect(x: float, y: float, size: float, r: float) -> str:
    """SVG path for a rounded square (clockwise from the top edge)."""
    side = size - 2 * r
    return (
        f"M{x + r},{y} h{side} a{r},{r} 0 0 1 {r},{r} v{side} "
        f"a{r},{r} 0 0 1 {-r},{r} h{-side} a{r},{r} 0 0 1 {-r},{-r} v{-side} "
        f"a{r},{r} 0 0 1 {r},{-r} z"
    )


def grid_path(margin: float, size: float, gap: float, r: float) -> str:
    """9 squares (3x3) as one path — one <path> instead of nine saves dex/parse time."""
    parts = []
    for row in range(3):
        for col in range(3):
            parts.append(rrect(margin + col * (size + gap), margin + row * (size + gap), size, r))
    return " ".join(parts)


def write(path: str, content: str) -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(content)
    print(f"  written: {os.path.relpath(path, ROOT)}")


def make_vectors() -> None:
    # Adaptive icon: 108x108 viewport, the visible area is the central 72
    # safe zone (18..90). The 3x3 grid sits exactly there.
    fg = VECTOR_HEAD.format(w=108, h=108, vw=108, vh=108)
    fg += f'    <path\n        android:fillColor="{GLYPH}"\n'
    fg += f'        android:pathData="{grid_path(18, 20, 6, 5)}" />\n</vector>\n'
    write(os.path.join(RES, "drawable", "ic_launcher_foreground.xml"), fg)

    # Legacy icon (API < 26): background + grid edge-to-edge in 24x24.
    legacy = VECTOR_HEAD.format(w=24, h=24, vw=24, vh=24)
    legacy += f'    <path\n        android:fillColor="{BG}"\n        android:pathData="M0,0h24v24h-24z" />\n'
    legacy += f'    <path\n        android:fillColor="{GLYPH}"\n'
    legacy += f'        android:pathData="{grid_path(3, 5, 1.5, 1.4)}" />\n</vector>\n'
    write(os.path.join(RES, "drawable", "ic_launcher_legacy.xml"), legacy)

    adaptive = (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- GENERATED by tools/make_assets.py — do not edit by hand. -->\n'
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '    <background android:drawable="@color/ic_launcher_background" />\n'
        '    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n'
        '    <!-- Monochrome layer (Android 13+): the system tints it itself.\n'
        '         The glyph is single-color and therefore works directly as a mask.\n'
        '         Without this entry lint reports MonochromeLauncherIcon. -->\n'
        '    <monochrome android:drawable="@drawable/ic_launcher_foreground" />\n'
        '</adaptive-icon>\n'
    )
    write(os.path.join(RES, "mipmap-anydpi-v26", "ic_launcher.xml"), adaptive)

    # anydpi without version qualifier: applies on API 21–25, where adaptive
    # icons are unknown. As a layer list, so that background + glyph also
    # come together there.
    fallback = (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- GENERATED by tools/make_assets.py — do not edit by hand. -->\n'
        '<layer-list xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '    <item android:drawable="@drawable/ic_launcher_legacy" />\n'
        '</layer-list>\n'
    )
    write(os.path.join(RES, "mipmap-anydpi", "ic_launcher.xml"), fallback)


def make_banner() -> None:
    """TV banner 320x180 (as prescribed by the Android TV leanback spec).

    The banner is the only graphic the system cannot derive from the icon
    — without it the app is missing from the TV apps row.
    """
    w, h = 320, 180
    img = Image.new("RGB", (w, h), BG)
    draw = ImageDraw.Draw(img)

    # Diagonal gradient as background (cheap: one line per column).
    top = (16, 21, 28)
    bottom = (7, 9, 13)
    for x in range(w):
        t = x / (w - 1)
        col = tuple(int(top[i] + (bottom[i] - top[i]) * t) for i in range(3))
        draw.line([(x, 0), (x, h)], fill=col)

    # 3x3 grid on the left, same geometry as the icon.
    cell, gap, radius = 22, 8, 5
    gx, gy = 34, (h - (3 * cell + 2 * gap)) // 2
    for row in range(3):
        for col in range(3):
            x = gx + col * (cell + gap)
            y = gy + row * (cell + gap)
            draw.rounded_rectangle([x, y, x + cell, y + cell], radius=radius, fill=GLYPH)

    font_path = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
    font = ImageFont.truetype(font_path, 34)
    text = "Navigate"
    box = draw.textbbox((0, 0), text, font=font)
    tx = gx + 3 * cell + 2 * gap + 26
    ty = (h - (box[3] - box[1])) // 2 - box[1]
    draw.text((tx, ty), text, font=font, fill=TEXT)

    out = os.path.join(RES, "drawable-nodpi", "banner.png")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    img.save(out, "PNG", optimize=True)
    print(f"  written: {os.path.relpath(out, ROOT)} ({w}x{h})")


def main() -> None:
    print("Navigate graphics:")
    make_vectors()
    make_banner()
    print("done.")


if __name__ == "__main__":
    main()
